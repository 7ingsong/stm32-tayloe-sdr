#!/usr/bin/env python3
"""Sine table for the digital fine-tuning NCO (src/nco_table.c).

Run from the repo root:  python3 tools/gen_nco_table.py > src/nco_table.c
"""
import numpy as np

N = 1024
s = np.round(np.sin(2 * np.pi * np.arange(N) / N) * 32767).astype(int)
rows = [", ".join(f"{v:6d}" for v in s[i:i + 12]) for i in range(0, N, 12)]
print("// Generated by tools/gen_nco_table.py -- do not edit by hand.")
print('#include "nco.h"\n')
print(f"// sin(2*pi*k/{N}), Q15; cos is the same table a quarter turn ahead")
print(f"const int16_t nco_sin[NCO_TABLE] = {{\n    " + ",\n    ".join(rows) + "\n};")
